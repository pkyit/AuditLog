package io.github.pkyit.auditlog.core.model;

/**
 * 审计结果。
 *
 * <p>审计记录必须能无歧义地回答「本次操作是否生效」。该结论不得由异常是否存在、
 * HTTP 状态码或业务状态码中的任一项单独推导：HTTP 200 可以携带业务错误码，
 * 异常也可能已被容器的错误处理吸收，不再体现于状态码。
 */
public enum Outcome {

	/** 操作成功。 */
	SUCCESS,

	/** 操作失败（业务异常或非预期异常）。 */
	FAILURE,

	/** 操作被拒绝（未认证 / 未授权 / 被限流 / 被风控拦截）。 */
	DENIED,

	/** 请求无效（参数绑定失败、报文格式错误等，未进入业务逻辑）。 */
	INVALID,

	/** 事务已回滚，操作未生效。 */
	ROLLBACK,

	/** 结果未知（采集链路自身失败，无法判定）。 */
	UNKNOWN
}
