package io.github.pkyit.auditlog.core.pipeline;

/**
 * 队列满时的背压策略。
 *
 * <p>「审计数据重要」与「业务 SLA 重要」在队列打满时必然冲突，框架无法替使用者消除该冲突，
 * 因此在装配时显式选择，并由所选策略承担各自代价：不丢数据必然依赖磁盘或阻塞业务线程，
 * 不影响业务则必然容忍数据丢失。
 */
public enum BackpressureStrategy {

	/**
	 * 写本地 WAL 日志兜底（默认）。
	 *
	 * <p>既不丢数据，也不阻塞业务线程。代价是需要磁盘空间；WAL 自身被压满时，
	 * 最末级降级为「内存计数 + 告警」。
	 *
	 * <p>适用于合规要求「不丢」的生产环境。
	 */
	SPILL,

	/**
	 * 阻塞等待队列有空位。
	 *
	 * <p>不丢数据、不占磁盘。代价是直接损耗业务 SLA：队列满意味着审计消费能力不足，
	 * 等待会拖慢业务线程；等待超过 {@code blockTimeoutMillis} 后降级为写 WAL。
	 *
	 * <p>适用于审计写入必须与业务同速、且可接受延迟上升的场景。
	 */
	BLOCK,

	/**
	 * 丢弃最旧的记录以腾出空间。
	 *
	 * <p>业务完全不受影响，最近事件得以保留。代价是被丢弃的记录确实丢失，
	 * 且丢失的是最早的事件，因此必须配合丢弃指标与告警使用。
	 *
	 * <p>适用于仅有「尽力审计」诉求、且明确接受丢失的场景。
	 */
	DROP_OLDEST,

	/**
	 * 直接丢弃当前记录。
	 *
	 * <p>业务完全不受影响，且保留最近事件。代价是被丢弃的记录确实丢失，
	 * 因此必须配合丢弃指标与告警使用。
	 */
	DROP_NEWEST,

	/**
	 * 抛出异常，中断业务请求。
	 *
	 * <p>审计零丢失，且失败立刻可见。代价是审计组件故障会直接导致业务不可用（可用性换一致性）：
	 * 队列满时抛出 {@link AuditPipeline.AuditUnavailableException}。
	 *
	 * <p>适用于强合规场景（监管要求无审计不得操作）。
	 */
	FAIL_FAST
}
